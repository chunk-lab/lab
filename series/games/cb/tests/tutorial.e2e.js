// チュートリアルを最後まで操作する
const { open, tapText } = require('./e2e_lib');
(async () => {
  const { browser, page, errors } = await open(390, 844);
  const S = n => page.screenshot({ path: __dirname + '/shots/' + n + '.png' });
  const G = () => page.evaluate(() => { const g = window.game._app.game; return g && { items: g.items.map(i => ({ id: i.id, text: i.text, x: i.x, y: i.y, kind: i.kind, t: i.chunk && i.chunk.t, slot: !!i.slot })), slots: g.slots.map(s => ({ x: s.rect.x + s.rect.w / 2, y: s.rect.y + s.rect.h / 2, item: s.item && s.item.text })), score: g.score }; });
  const find = async (text) => { const s = await G(); return s.items.find(i => i.text === text); };
  const tap = async (text) => { const i = await find(text); if (!i) throw new Error('no item ' + text); await page.mouse.click(i.x, i.y); await page.waitForTimeout(250); };
  const drag = async (a, b) => { await page.mouse.move(a.x, a.y); await page.mouse.down(); const n = 14; for (let k = 1; k <= n; k++) { await page.mouse.move(a.x + (b.x - a.x) * k / n, a.y + (b.y - a.y) * k / n); await page.waitForTimeout(16); } await page.waitForTimeout(90); await page.mouse.up(); await page.waitForTimeout(300); };
  await page.mouse.click(195, 500); await page.waitForTimeout(600);
  await tapText(page, 'あそぶ'); await page.waitForTimeout(500);
  await tapText(page, 'つぎへ'); await page.waitForTimeout(400); await S('10_tut1');
  await tap('the'); await tap('small'); await page.waitForTimeout(150); await S('11_chain'); await tap('cat'); await page.waitForTimeout(1300); await S('12_np');
  console.log('after NP:', (await G()).items.map(i => i.text + ':' + (i.t || 'w')).join(', '));
  let st = await G(); const np = st.items.find(i => i.t === 'NP'), vp = st.items.find(i => i.text === 'sleep');
  console.log('NP', np && np.text, 'VP', vp && vp.text);
  await drag(np, vp); await page.waitForTimeout(250); await S('14_sentence'); await page.waitForTimeout(1800); await S('15_after');
  await tapText(page, 'つぎへ'); await page.waitForTimeout(500);
  await tap('a'); await tap('a'); await page.waitForTimeout(150); await S('16_cycle'); await tap('dog'); await page.waitForTimeout(1200);
  st = await G(); console.log('step6 items:', st.items.map(i => i.text + ':' + (i.t || 'w')).join(', '));
  const np2 = st.items.find(i => i.t === 'NP'), run = st.items.find(i => i.text === 'run');
  await drag(np2, st.slots[1]); await page.waitForTimeout(300);
  st = await G(); await drag(st.items.find(i => i.text === 'run'), st.slots[2]); await page.waitForTimeout(400); await S('17_slots');
  await page.waitForTimeout(500);
  const pill = await page.evaluate(() => { const p = window.game._app.game.pill; return p && { x: p.x + p.w / 2, y: p.y + p.h / 2 }; });
  if (!pill) throw new Error('no pill'); await page.mouse.click(pill.x, pill.y); await page.waitForTimeout(400); await S('18_slotsent');
  await page.waitForTimeout(1800);
  st = await G(); const junk = st.items.find(i => i.text === 'into'); if (!junk) throw new Error('no junk');
  await drag(junk, await page.evaluate(() => { const g = window.game._app.game; return { x: 46, y: g.L.lane.y + g.L.lane.h * .55 }; })); await page.waitForTimeout(300); await S('18b_eat');
  await page.waitForTimeout(1200);
  await tapText(page, 'はじめる!'); await page.waitForTimeout(700); await S('19_modes');
  console.log('score', (await G()) ? 'game still' : 'no game', 'errors:', errors);
  await browser.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
