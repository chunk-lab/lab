// 哲学者「人生を左右する」。公園で3つの問い。なんでも深読みしてほめてくる→帰り道は右か左か、で夕方まで悩む。
const P = Math.PI;
export async function tetsuStory(d, ctx = {}) {
  const T = 'tetsu', me = (ctx.name && ctx.name()) || 'あなた';
  const two = () => d.shot('me', T, { yaw: 0.9, dist: 7, h: 2.3, look: 1.0 });
  await d.fade(true, 0.01);
  d.only(['tetsu']);
  d.hour(14); d.wx('sun', 'snap');
  // ---- こもれび公園 ----
  d.place(T, 44, 12.6, 0); d.place('me', -60, 40, 0);
  d.shot(T, null, { yaw: 0.6, dist: 6, h: 2.0, look: 1.4 });
  await d.title('哲学者', '人生を左右する');
  await d.fade(false, 1.2);
  await d.say('narr', 'こもれび公園。\n哲学者が、ベンチの前で 空を見上げている。');
  d.place('me', 45.6, 14.4, P); d.face('me', T); d.face(T, 'me');
  two();
  await d.say('me', '「こんにちは」');
  await d.say(T, '「やあ、こんにちは。……ちょうどいい。\n少し、考えごとに 付き合ってくれないかな」');
  // ---- 問い1 ----
  await d.say(T, '「私たちは、いつも 思い込みに支配されている」');
  const a = await d.choose(T, '「君にとって、本当に大切なものは 何かな？」', ['友だち', 'お金', 'おやつ', '……わからない']);
  const A = [
    ['「なるほど……。人は、ひとりでは"自分"にすら なれない。\n君は、それを もう知っているんだね」', '(そこまでは、考えてなかったけど……)'],
    ['「ほう……。お金とは、だれかの時間と 交換できる約束だ。\n君は、時間こそが いちばん大切だと 言いたいんだね」', '(言ってないけど……)'],
    ['「なるほど……。一瞬の幸福こそ、永遠だと。\n君は、"今"を生きているのだね」', '(なんとなく選んだだけ、なんだけど……)'],
    ['「すばらしい。"わからない"と言えるのは、\n思い込みから 自由だという あかしだ」', '(ほんとに、わからなかっただけ なんだけど……)'],
  ][a];
  await d.say(T, A[0]);
  await d.say('me', A[1]);
  await d.say('narr', '哲学者は、満足そうに うなずいた。');
  // ---- 問い2 ----
  await d.say(T, '「宇宙が膨張しているのではなく、\n私たちの認識が、縮んでいるのかもしれない」');
  await d.say(T, '「そうやって、常識を 疑うのだ」');
  const b = await d.choose('me', `${me}は……`, ['「わかる気がする」', '「さっぱり分からない」']);
  await d.say(T, b === 0 ? '「おお……！ 君は、感じることで わかる人なんだね。\n言葉より先に、わかってしまう。うらやましいよ」' : '「それでいい。分からないと感じたとき、\n君の常識は、もう ゆらぎ始めているのだから」');
  await d.say('me', '(……ほめられた？)');
  // ---- 問い3 ----
  await d.say(T, '「正しいか、間違っているかなんて 関係ない。\n最後に残るのは、君の意思だよ」');
  await d.say(T, '「さて、そろそろ帰ろうか。\n……帰り道は、右と左、どちらがいいと思う？」');
  const c = await d.choose('me', `${me}は……`, ['「右！」', '「左！」']);
  await d.say('me', c === 0 ? '「右で！」' : '「左で！」');
  await d.say(T, '「……ふむ」');
  await d.say('narr', '哲学者は、腕を組んで 考えこんでしまった。');
  await d.say(T, '「右には、夕日がある。左には、家路がある。\n……どちらを選ぶかで、今日という日の 意味が変わってしまう」');
  // ---- 夕方 ----
  d.hideBox(); await d.fade(true, 0.9);
  d.hour(17.4); d.caption('夕方');
  d.shot(T, null, { yaw: 2.6, dist: 6.5, h: 2.0, look: 1.3 });
  await d.fade(false, 0.9);
  await d.say('narr', '夕方。\n哲学者は、まだ 右と左のあいだに 立っていた。');
  d.caption('');
  two();
  await d.say(T, '「この選択が、人生を"左右"するかと思うと……\nなかなか、選べないのだよ」');
  await d.say('me', '(さっき、"最後に残るのは 君の意思だ"って 言ってたのに……)');
  await d.say('me', '(考えすぎないほうが いいことも、あるんだなぁ)');
  await d.friend(T, 5);
  await d.endCard('哲学者「人生を左右する」', 'おしまい');
}
